/** English text is the key; a pipe line registers both spellings. */
const DICT: Dict = {}
for (const line of RAW.split('\n')) {
  const row = line.trim()
  if (!row) continue
  const eq = row.indexOf('=')
  if (eq <= 0) continue
  const value = row.slice(eq + 1)
  for (const k of row.slice(0, eq).split('|')) DICT[k.trim()] = value
}

